const pack = game.packs.get(PACK_ID);
if (!pack) {
  ui.notifications.error(`Compendium "${PACK_ID}" not found. Check that system.json declares it and Foundry has been restarted.`);
  return;
}

await pack.getDocuments();
const existingNames = new Set(pack.contents.map(i => i.name));

/** Find or create a folder inside the compendium. Returns its id. */
const folderIds = new Map();
async function folderIdFor(name) {
  if (folderIds.has(name)) return folderIds.get(name);
  let folder = pack.folders.find(f => f.name === name);
  folder ??= await Folder.create({ name, type: "Item" }, { pack: PACK_ID });
  folderIds.set(name, folder.id);
  return folder.id;
}

const toCreate = [];
for (const { name, folder, linked, ...fields } of WEAPONS) {
  if (existingNames.has(name)) continue;
  toCreate.push({
    name,
    type: "weapon",
    folder: folder ? await folderIdFor(folder) : null,
    system: { ...DEFAULTS, ...fields },
    flags: linked ? { "mutant-chronicles": linked } : {}
  });
}

if (toCreate.length === 0) {
  ui.notifications.info("MC3 Weapons compendium is already complete — nothing to create.");
  return;
}

await Item.createDocuments(toCreate, { pack: PACK_ID });
ui.notifications.info(`MC3 Weapons | Created ${toCreate.length} weapon(s) in the compendium.`);
